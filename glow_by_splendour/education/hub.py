def get_all_articles():
    """Returns the list of all articles."""
    return educational_articles

def get_article_by_id(article_id):
    """Returns a specific article by its ID."""
    for article in educational_articles:
        if article["article_id"] == article_id:
            return article
    return None

def search_articles(query):
    """
    A simple search function that returns articles where the query
    matches words in the title, summary, or tags (case-insensitive).
    """
    if not query:
        return get_all_articles()
    
    query = query.lower()
    search_results = []
    for article in educational_articles:
        if query in article["title"].lower() or \
           query in article["summary"].lower() or \
           any(query in tag.lower() for tag in article["tags"]):
            search_results.append(article)
    return search_results
